import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

if (!process.argv[2]) throw new Error('Pass the path to the canonical Izumi repository.')
const source = resolve(process.argv[2])
const git = (...args) => execFileSync('git', ['-C', source, ...args], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
const gitCommit = git('rev-parse', 'HEAD').trim()
const read = path => git('show', `${gitCommit}:${path}`)
const workerBundle = read('src-tauri/src/cloudflare_worker_bundle.mjs')
const config = JSON.parse(read('cloudflare-sync-worker/wrangler.jsonc'))
const version = JSON.parse(read('cloudflare-sync-worker/package.json')).version
const index = read('cloudflare-sync-worker/src/index.js')
if (!index.includes(`const VERSION = '${version}'`) || !workerBundle.startsWith('// izumi-cloudflare-source-sha256:')) {
  throw new Error('The canonical Worker version or generated bundle is inconsistent.')
}
const paths = git('ls-tree', '-r', '--name-only', gitCommit, 'cloudflare-sync-worker/migrations').trim().split(/\r?\n/)
const migrations = paths.filter(path => /\/\d{4}_[a-z0-9_]+\.sql$/.test(path)).sort()
  .map(path => ({ name: path.split('/').pop().replace(/\.sql$/, ''), sql: read(path) }))
if (!migrations.length) throw new Error('The canonical Worker migrations are missing.')
const data = { workerBundle, compatibilityDate: config.compatibility_date, migrations, gitCommit }
const output = resolve(import.meta.dirname, '../installer/cloudflare-source/src/generated/izumi-artifacts.ts')
writeFileSync(output, '// Generated by scripts/sync-worker-artifacts.mjs from committed canonical Izumi source.\n'
  + '// Release snapshot shared by the desktop and mobile installers.\n'
  + `export const izumiArtifacts = ${JSON.stringify(data)} as const\n`)
console.log(`Updated installer Worker to ${version} from ${gitCommit.slice(0, 12)}.`)
